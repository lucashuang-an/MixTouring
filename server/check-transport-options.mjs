assert.deepEqual(connectionOptions([source('丙城到乙城火车查询','other')],scope),[]);
assert.deepEqual(connectionOptions(rows,{...scope,no_self_drive:true}).map(o=>o.mode),['rail','plane']);
assert.deepEqual(connectionOptions(rows,{...scope,exclude_road:true}).map(o=>o.mode),['rail','plane']);
assert.deepEqual(connectionOptions(rows,{...scope,mode:'road'}),[],'自驾不是公路客运');
assert.deepEqual(connectionOptions(rows.map(s=>({...s,temporal:{state:'future'}})),scope),[]);
const queries=[];
const result=await searchTransportSources(scope,async(q,o)=>{queries.push({q,o});return rows.map(s=>({title:s.title,link:s.url,content:s.excerpt}));},{now,useCache:false,readPage:null});
assert.equal(queries.length,4,'未知方式最多三种交通方向加一次社区补充');
assert(queries.every(q=>q.q.includes('甲城') && q.q.includes('乙城')));
assert.equal(result.connection_options.length,3);assert.equal(result.sources.length,0,'查询页不升级成近期运营证据');
assert.equal(transportSearchEvidence([result.retrieval_id],{route:['甲城','乙城'],now}).length,0);
assert.equal(resolveTransportSearch({ids:[result.retrieval_id],legs:[{...scope,mode:'unknown'}]},{now}).records[0].connection_options.length,3);
assert.equal(resolveTransportSearch({ids:[result.retrieval_id],legs:[{...scope,mode:'unknown',no_self_drive:true}]},{now}).records.length,0);
assert(!transportSearchCovered([result.retrieval_id],{...scope,mode:'unknown',no_self_drive:true,now}));
const restricted=await searchTransportSources({...scope,no_self_drive:true},async(q)=>{assert(!q.includes('自驾'));return rows.map(s=>({title:s.title,link:s.url,content:s.excerpt}));},{now,useCache:false,readPage:null});
assert(!restricted.connection_options.some(o=>o.mode==='drive'));
const html=workspace.transportHtml(['甲城','乙城'],null,[{...scope,live:result}]);
for(const label of ['火车','飞机','自驾'])assert(html.includes(label));
assert(html.includes('查询入口'));assert(!html.includes('尚无近期运营资料'));assert(!html.includes('<h4>旅行者经验</h4>'));
assert(!workspace.transportHtml(['甲城','乙城'],null,[{...scope,live:result,no_self_drive:true}]).includes('自驾'));
const s=draftQueryScope({route:['甲城','乙城'],constraints:{no_self_drive:true}},now);assert(s.legs[0].no_self_drive);
const updated=draftResearchChanges({conversation:{draft:{route:['甲城','乙城']}},constraints:{}},{status:'ok',conversation:{draft:{route:['甲城','乙城']}},patch:{constraints:{no_self_drive:true}}},null,{now});assert.equal(updated.queries.length,1);
