import assert from 'node:assert/strict';
import {connectionOptions} from './lib/transport-options.mjs';
import {searchTransportSources,resolveTransportSearch,transportSearchEvidence,transportSearchCovered} from './lib/transport-search.mjs';
import {draftQueryScope,draftResearchChanges} from './lib/draft-research.mjs';
import workspace from '../mixtouring-hifi/assets/route-workspace.js';
const now=Date.parse('2026-10-31T00:00:00Z');
const source=(title,path,excerpt=title)=>({title,url:'https://'+path+'.example.org/reference',excerpt,published_at:null,temporal:{state:'undated'}});
const rows=[source('甲城到乙城火车时刻表查询','rail'),source('甲城到乙城机票航班查询','plane'),source('甲城自驾到乙城路线','drive')];
const scope={from:'甲城',to:'乙城'};
const options=connectionOptions(rows,scope);
assert.deepEqual(options.map(o=>o.mode),['rail','plane','drive']);assert(options.every(o=>o.basis==='search_entry' && o.evidence_state==='explore'));
assert.deepEqual(connectionOptions(rows,{from:'乙城',to:'甲城'}),[],'不能反转来源证明返程');
assert.deepEqual(connectionOptions([],scope),[],'无资料不能套入三种预置方案');
